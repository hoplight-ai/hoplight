#!/usr/bin/env node
// check-no-drafts-public.mjs: a draft cannot go public on hoplight.ai by an ordinary push.
//
//   node scripts/check-no-drafts-public.mjs               checks public/ (runs in prebuild and CI)
//   node scripts/check-no-drafts-public.mjs --dir <path>  checks another folder (tests, a sibling checkout)
//
// WHY. Every file under public/ is served on hoplight.ai to anyone with the address, with no sign-in.
// Nothing told a draft for a named outside party apart from a site page. On 2026-09-23 a funder
// one-pager went up that way, on 2026-09-24 a funder brief went up that way and had to be pulled
// (commit 3119855), and on 2026-09-25 the brief's files were back in the folder, untracked, one
// `git add public/` from going up again. Whit, 2026-09-24: "#1 never ever put a fucking public site
// up without my explicity approval". Portfolio AUDITPUB1 (2026-09-25) made the rule a machine check.
//
// THE RULE. Drafts in this repo are named `<what>-YYYY-MM-DD`. Any file under public/ whose path
// carries a `-YYYY-MM-DD` date fails the build unless an entry below starts its path. An entry says,
// in one line, who the file is public for. A draft for review goes to visualizations/private/
// (Basic Auth), not here.
//
// The check reads the folder on disk, not git, so an untracked draft fails the local build too.
// A date written with spaces (`Screenshot 2026-06-26 at ...`) is not a draft name and is not caught.

import { readdirSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

// Each `match` is the start of a path relative to public/, so one entry covers a page, its PDF and
// its manifest. Keep this list short. Adding a line here is putting a page on the public internet.
export const ALLOW = [
  {
    match: 'hoplight-brand-tokens-2026-09-20',
    publicFor:
      'any session or tool that reads the Hoplight brand tokens by URL (generated by scripts/build-brand-tokens.mjs, lane dispatch1, 2026-09-20); machine-read reference, not a draft for an outside party',
  },
  {
    // Funder one-pager for Kuhan Jeyapragasan's advisers. No typed approval or "sent it" from Whit
    // was found in the chat archive, but he may have sent the link by hand. A gated copy sits at
    // visualizations/private/hoplight/. Yes from Whit: delete this entry, remove the three files,
    // and redirect both addresses to the gated copy. No: replace this line with his words.
    match: 'soft-trump-voter-ads-one-pager-2026-09-23',
    publicFor: "pending Whit's yes, dispatcher asks 2026-09-25",
  },
  {
    // Productized-services page mockup, "for review" (a2b3ed2, 2026-09-09). Found by this check,
    // outside the AUDITPUB1 brief's named set; no quote from Whit sharing it was found. Same
    // question, same fix as the one-pager above.
    match: 'productized-services-2026-09-09',
    publicFor: "pending Whit's yes, dispatcher asks 2026-09-25",
  },
];

const DATED = /-\d{4}-\d{2}-\d{2}/;

function walk(dir, prefix, out) {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const rel = prefix ? `${prefix}/${e.name}` : e.name;
    if (e.isDirectory()) walk(join(dir, e.name), rel, out);
    else out.push(rel);
  }
  return out;
}

export function listFiles(publicDir) {
  return walk(publicDir, '', []).sort();
}

export function findDrafts(publicDir, allow = ALLOW) {
  return listFiles(publicDir).filter(
    (rel) => DATED.test(rel) && !allow.some((a) => rel.startsWith(a.match)),
  );
}

function main(argv) {
  const i = argv.indexOf('--dir');
  const root = join(dirname(fileURLToPath(import.meta.url)), '..');
  const dir = i >= 0 && argv[i + 1] ? resolve(argv[i + 1]) : join(root, 'public');
  const files = listFiles(dir);
  const bad = findDrafts(dir);
  if (bad.length) {
    console.log(`check-no-drafts-public: FAIL, ${bad.length} dated draft file(s) under ${dir} would be served publicly:`);
    for (const f of bad) console.log(`  ${f}`);
    console.log('Move each one to visualizations/private/ (password-gated), or, only with Whit\'s yes,');
    console.log('add an entry to ALLOW in scripts/check-no-drafts-public.mjs saying who it is public for.');
    return 1;
  }
  const allowed = files.filter((f) => DATED.test(f)).length;
  console.log(`check-no-drafts-public: PASS, ${files.length} files scanned, ${allowed} dated file(s) on the allow list (${ALLOW.length} entries)`);
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exit(main(process.argv.slice(2)));
}
