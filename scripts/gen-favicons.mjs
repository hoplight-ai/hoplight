import sharp from "sharp";
import { readFileSync, writeFileSync, statSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const pub = (name) => join(root, "public", name);

const svg = readFileSync(pub("favicon.svg"));
const sizes = {
  "favicon-16.png": 16,
  "favicon-32.png": 32,
  "favicon-48.png": 48,
  "apple-touch-icon.png": 180,
  "favicon-192.png": 192,
  "favicon-512.png": 512,
};
for (const [name, size] of Object.entries(sizes)) {
  await sharp(svg, { density: 384 }).resize(size, size).png().toFile(pub(name));
}

// Social card
const og = readFileSync(pub("og.svg"));
await sharp(og, { density: 144 }).resize(1200, 630).png().toFile(pub("og.png"));

// favicon.ico — added 2026-09-16 (performance review: the previous favicon.ico, generated by some
// earlier tool, carried an uncompressed 256x256 layer and weighed 285,478 bytes; browsers fetch
// /favicon.ico automatically on most first visits regardless of the modern <link> icon tags, so
// that was the single largest static asset on the domain after the two hero screenshots).
// sharp cannot write .ico directly, so this builds the container by hand: the classic Windows
// ICONDIR format supports embedding plain PNG-compressed images per entry (any reader from Vista
// onward accepts this), so no separate BMP/DIB encoding is needed — the three PNGs already
// generated above are simply packed with a small binary header.
function buildIco(entries) {
  const count = entries.length;
  const headerSize = 6 + 16 * count;
  let offset = headerSize;
  const dirEntries = [];
  const imageBuffers = [];
  for (const { size, buffer } of entries) {
    const dir = Buffer.alloc(16);
    dir.writeUInt8(size >= 256 ? 0 : size, 0); // width (0 means 256)
    dir.writeUInt8(size >= 256 ? 0 : size, 1); // height
    dir.writeUInt8(0, 2); // color count (0 = no palette, true color)
    dir.writeUInt8(0, 3); // reserved
    dir.writeUInt16LE(1, 4); // color planes
    dir.writeUInt16LE(32, 6); // bits per pixel
    dir.writeUInt32LE(buffer.length, 8); // size of image data
    dir.writeUInt32LE(offset, 12); // offset of image data from start of file
    dirEntries.push(dir);
    imageBuffers.push(buffer);
    offset += buffer.length;
  }
  const header = Buffer.alloc(6);
  header.writeUInt16LE(0, 0); // reserved
  header.writeUInt16LE(1, 2); // type: 1 = icon
  header.writeUInt16LE(count, 4); // image count
  return Buffer.concat([header, ...dirEntries, ...imageBuffers]);
}

const icoBeforeBytes = (() => {
  try {
    return statSync(pub("favicon.ico")).size;
  } catch {
    return null;
  }
})();

const icoSizes = [16, 32, 48];
const icoEntries = [];
for (const size of icoSizes) {
  const buffer = await sharp(svg, { density: 384 }).resize(size, size).png().toBuffer();
  icoEntries.push({ size, buffer });
}
const ico = buildIco(icoEntries);
writeFileSync(pub("favicon.ico"), ico);

console.log(
  `favicon.ico written: ${ico.length} bytes (16+32+48px only)` +
    (icoBeforeBytes ? `, was ${icoBeforeBytes} bytes before` : ""),
);

console.log("favicons + og written");
